import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'crypto';
import { isEmailConfigured, sendEmail } from '../src/lib/server/email/index.js';

describe('Phase 5: Production Security, Health & Email Delivery', () => {
	it('safely evaluates transactional email configuration without throwing', async () => {
		const configured = isEmailConfigured();
		assert.equal(typeof configured, 'boolean');

		// When unconfigured, sendEmail must return a structured graceful error without throwing
		if (!configured) {
			const res = await sendEmail({
				to: 'test@example.com',
				subject: 'Test Subject',
				html: '<p>Test</p>'
			});

			assert.equal(res.sent, false);
			assert.equal(res.reason, 'EMAIL_SERVICE_NOT_CONFIGURED');
			assert.ok(res.error.includes('RESEND_API_KEY'));
		}
	});

	it('hashes password reset tokens with SHA-256 for unpredictable, tamper-proof storage', () => {
		const rawToken = crypto.randomBytes(32).toString('hex');
		const hash1 = crypto.createHash('sha256').update(rawToken).digest('hex');
		const hash2 = crypto.createHash('sha256').update(rawToken).digest('hex');

		assert.equal(hash1, hash2, 'Hash must be deterministic');
		assert.equal(hash1.length, 64, 'SHA-256 produces 64 hex characters');
		assert.notEqual(hash1, rawToken, 'Raw reset token must never be stored directly in plaintext');
	});

	it('validates CSRF protection logic rejects untrusted origins on state-changing endpoints', () => {
		const checkOrigin = (requestOrigin, appOrigin) => {
			if (!requestOrigin) return true; // same-origin or direct
			if (requestOrigin === appOrigin) return true;
			if (requestOrigin.startsWith('http://localhost:') || requestOrigin.startsWith('http://127.0.0.1:')) {
				return true;
			}
			return false;
		};

		assert.equal(checkOrigin('https://evil-attacker.com', 'https://scanai.vercel.app'), false);
		assert.equal(checkOrigin('https://scanai.vercel.app', 'https://scanai.vercel.app'), true);
		assert.equal(checkOrigin('http://localhost:5173', 'http://localhost:5173'), true);
		assert.equal(checkOrigin(null, 'https://scanai.vercel.app'), true);
	});

	it('ensures health status schema does not disclose internal credentials or database strings', () => {
		// Mock health check structure generated by /api/health
		const healthPayload = {
			status: 'healthy',
			version: '1.0.0',
			uptimeSeconds: 120,
			timestamp: new Date().toISOString(),
			services: {
				database: 'connected',
				providers: {
					chatgpt: true,
					claude: true,
					gemini: true
				}
			}
		};

		assert.equal(healthPayload.status, 'healthy');
		assert.equal(healthPayload.services.database, 'connected');

		const serialized = JSON.stringify(healthPayload);
		assert.equal(serialized.includes('mongodb://'), false, 'Must not leak MongoDB connection string');
		assert.equal(serialized.includes('mongodb+srv://'), false, 'Must not leak SRV connection string');
		assert.equal(serialized.includes('password'), false, 'Must not leak credentials');
		assert.equal(serialized.includes('AIzaSy'), false, 'Must not leak Gemini keys');
		assert.equal(serialized.includes('sk-'), false, 'Must not leak OpenAI/Anthropic keys');
	});
});
